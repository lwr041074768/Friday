import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import ts from "typescript";
const modules = {};
for (const name of ["xrd-reference-types", "xrd-experimental-peaks"]) {
  let code = ts.transpileModule(await readFile(new URL(`../lib/${name}.ts`, import.meta.url), "utf8"), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
  code = code.replace(/(from\s*["'])\.\/([^"']+)(["'])/g, (_, start, dependency, end) => { assert.ok(modules[dependency]); return `${start}${modules[dependency]}${end}`; });
  modules[name] = `data:text/javascript;base64,${Buffer.from(code).toString("base64")}`;
}
const { inspectExperimentalPeaks } = await import(modules["xrd-experimental-peaks"]);
const options = { wavelength: 1.5406, toleranceDeg: 0.1, minProminencePercent: 5, minSeparationDeg: 0.2 };
const curve = values => ({ id: "test", name: "test", points: values.map((current, index) => ({ e: 20 + index, current })), visible: true });
const reference = angles => ({ id: "reference", source: "cod", wavelength: 1.5406, visible: true, peaks: angles.map(twoTheta => ({ twoTheta, d: 1.5406 / (2 * Math.sin(twoTheta * Math.PI / 360)), intensity: 100 })) });
const raw = curve([-10, -10, 0, -10, -10, -5, -5, -5, -10, -9.9, -10, -10]);
const original = structuredClone(raw);
const found = inspectExperimentalPeaks(raw, [reference([22.03])], options);
assert.deepEqual(found.peaks.map(peak => peak.x), [22, 26]);
assert.deepEqual(found.peaks.map(peak => peak.index), [2, 6]);
assert.deepEqual(found.peaks.map(peak => peak.prominence), [10, 5]);
assert.deepEqual(found.peaks.map(peak => peak.matched), [true, false]);
assert.ok(Math.abs(found.peaks[0].nearestReferenceDelta + 0.03) < 1e-8);
assert.deepEqual(raw, original, "Original raw intensities and point order are unchanged");
const reverse = { ...raw, points: [...raw.points].reverse() };
const reversed = inspectExperimentalPeaks(reverse, [reference([22.03])], options);
assert.deepEqual(reversed.peaks.map(peak => peak.x), [22, 26]);
assert.deepEqual(reversed.peaks.map(peak => peak.index), [9, 5]);
const hidden = { ...reference([22, 26]), visible: false };
const none = inspectExperimentalPeaks(raw, [hidden], options);
assert.ok(none.peaks.every(peak => !peak.matched && peak.nearestReferenceDelta === undefined));
assert.ok(none.warnings.some(warning => /没有显示/.test(warning)));
const weak = inspectExperimentalPeaks(raw, [], { ...options, minProminencePercent: 60 });
assert.equal(weak.peaks.length, 1);
const separated = inspectExperimentalPeaks(raw, [], { ...options, minSeparationDeg: 5 });
assert.equal(separated.peaks.length, 1);
assert.equal(separated.peaks[0].x, 22);
assert.equal(inspectExperimentalPeaks(curve([1, 1, 1, 1]), [], options).peaks.length, 0);
assert.equal(inspectExperimentalPeaks(curve([0, 1, 2, 3]), [], options).peaks.length, 0, "Scan endpoints are not invented as local peaks");
const shortPlateau = inspectExperimentalPeaks(curve([0, 5, 5, 0]), [], options);
assert.equal(shortPlateau.peaks[0].x, 21, "Plateau center is an actual sample, never an interpolated x");
const higher = inspectExperimentalPeaks(curve([0, 4, 3, 8, 0]), [], options);
assert.deepEqual(higher.peaks.map(peak => peak.prominence), [1, 8], "Valley search stops at the higher peak for shoulder prominence");
const capped = inspectExperimentalPeaks(curve([0, 3, 0, 5, 0]), [], { ...options, maxPeaks: 1 });
assert.equal(capped.peaks[0].x, 23);
assert.ok(capped.warnings.some(warning => /上限/.test(warning)));
assert.throws(() => inspectExperimentalPeaks({ ...raw, points: [{ e: 20, current: 0 }, { e: 21, current: 3 }, { e: 20, current: 0 }] }, [], options), /严格单调/);
assert.throws(() => inspectExperimentalPeaks({ ...raw, points: [{ e: 20, current: 0 }, { e: 20, current: 3 }, { e: 21, current: 0 }] }, [], options), /重复/);
assert.throws(() => inspectExperimentalPeaks({ ...raw, points: [{ e: 20, current: 0 }, { e: 21, current: NaN }, { e: 22, current: 0 }] }, [], options), /非有限/);
assert.throws(() => inspectExperimentalPeaks(raw, [], { ...options, minProminencePercent: 0 }), /突出度/);
// 200k-point bound verifies linear storage and no recursive per-point scanning.
const big = { ...raw, points: Array.from({ length: 200000 }, (_, index) => ({ e: index / 2000, current: index === 50000 ? 20 : 0 })) };
assert.equal(inspectExperimentalPeaks(big, [], options).peaks[0].index, 50000);
console.log("Raw XRD peak inspection checks passed: signed baseline, noise threshold, plateaus, exact prominence, descending provenance, visible-card matching, bounded display and monotonic/gap validation.");
